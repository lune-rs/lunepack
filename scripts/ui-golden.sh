#!/usr/bin/env bash
# The golden frames of the UI screens (M6-D9): renders every screen and transition headless and
# compares it with the PNGs of this OS's golden set in crates/lunepack-ui-luneui/tests/golden
# (linux-aarch64, linux-x86_64, macos, windows; each OS compares against its own adapter and Linux
# against the set of its own CPU, see the README there).
#
#   scripts/ui-golden.sh                  macOS: natively against the macos set (Metal, the
#                                         cross-adapter tolerance); fails, saying how to seed it,
#                                         while that set does not exist;
#                                         Linux: in the reference Docker image (the same as --docker)
#   scripts/ui-golden.sh --docker         in the reference image against the linux set of the
#                                         image's CPU (lavapipe, the exact tolerance)
#   scripts/ui-golden.sh --docker --write rewrite that linux set from the reference image
#
# The linux sets are generated by the reference image only, so --write needs --docker, and it
# rewrites the set of the CPU Docker runs the image on (linux-aarch64 on an arm64 Mac,
# linux-x86_64 on an x86-64 host); the other CPU's set and the macos and windows sets come from
# the frames CI uploads (the README says how). The renders of the run (every
# frame, as PNG) are left in target/ui-golden-out for inspection and for CI to upload.
#
# The Docker mode builds the image `lunepack-rs-ui-golden:<hash>` from scripts/ui-golden.Dockerfile
# (the gate's pinned base plus mesa-vulkan-drivers; once per Dockerfile change), runs `docker run
# --rm` with the worktree read-only and keeps its build output in two named volumes of its own
# (lunepack-rs-ui-golden-target, lunepack-rs-ui-golden-cargo), distinct from the gate's. It uses the
# base's multi-platform index digest and never forces --platform, so on an arm64 Mac Docker runs
# the arm64 variant (lavapipe renders arm64 and x86-64 slightly differently, a channel delta of 2
# on a fraction of a percent of the pixels, hence one set per CPU). It never prunes and never
# removes images, volumes or containers. bash 3.2 compatible.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
top=$PWD

usage() {
  echo "usage: scripts/ui-golden.sh [--docker [--write]]" >&2
}

die() {
  echo "ui-golden: $*" >&2
  exit 1
}

docker_mode=0
write=0
while [ "$#" -gt 0 ]; do
  case $1 in
    --docker)
      docker_mode=1
      shift
      ;;
    --write)
      write=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage
      exit 2
      ;;
  esac
done
if [ "$write" -eq 1 ] && [ "$docker_mode" -eq 0 ]; then
  usage
  exit 2
fi
if [ "$(uname -s)" = Linux ]; then
  docker_mode=1
fi

golden_root=crates/lunepack-ui-luneui/tests/golden
out_dir=$top/target/ui-golden-out
mkdir -p "$out_dir"

if [ "$docker_mode" -eq 0 ]; then
  [ "$(uname -s)" = Darwin ] || die "natively this script runs on macOS only (use --docker)"
  echo "ui-golden: native run against the macos set (the cross-adapter tolerance)"
  LUNEPACK_GOLDEN_CLASS=cross LUNEPACK_GOLDEN_OUT=$out_dir \
    cargo test -p lunepack-ui-luneui --locked --test golden -- --ignored
  exit 0
fi

command -v docker >/dev/null 2>&1 || die "docker is not installed"
# The container runs as root with every capability dropped, so on a Linux host (no Docker
# Desktop file sharing) it can write to /out only when the directory lets anyone write. Sticky,
# so the directory's owner can still remove what the container wrote.
if [ "$(uname -s)" = Linux ]; then
  chmod 1777 "$out_dir"
fi
docker info >/dev/null 2>&1 || die "the Docker daemon is not running"
dockerfile=scripts/ui-golden.Dockerfile
if command -v shasum >/dev/null 2>&1; then
  hash=$(shasum -a 256 "$dockerfile" | cut -c 1-12)
else
  hash=$(sha256sum "$dockerfile" | cut -c 1-12)
fi
image=lunepack-rs-ui-golden:$hash
if docker image inspect "$image" >/dev/null 2>&1; then
  echo "ui-golden: using docker image $image"
else
  echo "ui-golden: building docker image $image from $dockerfile"
  docker build --quiet -t "$image" - <"$dockerfile" >/dev/null
fi

# The linux set of the image's CPU is mounted writable on top of the read-only source only to
# rewrite it. The image's architecture is what Docker resolved (never forced), not the host's.
mounts=
write_env=
if [ "$write" -eq 1 ]; then
  case $(docker image inspect --format '{{.Architecture}}' "$image") in
    arm64) golden_dir=$golden_root/linux-aarch64 ;;
    amd64) golden_dir=$golden_root/linux-x86_64 ;;
    *) die "the image's CPU has no linux golden set" ;;
  esac
  mkdir -p "$top/$golden_dir"
  mounts="-v $top/$golden_dir:/src/$golden_dir"
  write_env="-e LUNEPACK_WRITE_GOLDENS=1"
fi

# RUSTUP_TOOLCHAIN makes rustup use the image's own 1.99.1 instead of installing what
# rust-toolchain.toml lists. No host env is passed, no capabilities, no new privileges.
# shellcheck disable=SC2086
docker run --rm \
  --name "lunepack-rs-ui-golden-$$" \
  --cap-drop ALL \
  --security-opt no-new-privileges \
  -v "$top":/src:ro \
  $mounts \
  -v "$out_dir":/out \
  -v lunepack-rs-ui-golden-target:/target \
  -v lunepack-rs-ui-golden-cargo:/cargo-home \
  -e CARGO_TARGET_DIR=/target \
  -e CARGO_HOME=/cargo-home \
  -e RUSTUP_TOOLCHAIN=1.99.1 \
  -e LUNEPACK_GOLDEN_CLASS=exact \
  -e LUNEPACK_GOLDEN_OUT=/out \
  $write_env \
  -w /src \
  "$image" \
  bash -c 'echo "ui-golden: Mesa $(dpkg-query -W -f="\${Version}" mesa-vulkan-drivers)"; exec cargo test -p lunepack-ui-luneui --locked --test golden -- --ignored'
